"""
PURGE JUNK ARTICLES — remove template-filler posts from the blog.

19 articles were generated by the broken template fallback and read like
"Why Does Pre-Earnings Stock Picks: The Complete Guide for 2026". They are
indexed by Google and carry the scaled-content-abuse pattern.

Plan:
  - Delete the generated .html files
  - Remove entries from blog/index.json (which also removes them from the
    generated sitemap.xml)
  - Add 301 redirects for every purged slug -> /blog, so any ranking or
    inbound link still resolves instead of 404ing
  - Keep a manifest at blog/retired_slugs.json so the redirect list is
    auditable and survives restarts

Only touches articles the quality gate classifies as junk. Real articles
(the SMCI piece, the November earnings piece, BILI/DDOG wins) are untouched.

Usage: python purge_junk_articles.py [--dry-run]
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import quality_gate as qg  # noqa: E402

REPO = Path(r"C:\Users\Tyler_AI\ai-market-cap")
BLOG = REPO / "blog"
INDEX = BLOG / "index.json"
PUB = Path(__file__).resolve().parent / "article_queue" / "published"
MANIFEST = BLOG / "retired_slugs.json"

# Written into scanner_web.py as a redirect table — kept here for reference.
REDIRECT_NOTE = "301 table lives in scanner_web.py RETIRED_SLUGS"


def is_junk(article):
    """Template filler = banned phrase in body OR spun title pattern."""
    title = article.get("title", "") or ""
    content = article.get("content", "") or ""
    plain = content.lower()
    tl = title.lower()

    if "continues to be one of the most discussed" in plain:
        return True
    if "the complete guide for 2026" in tl:
        return True
    if "for beginners" in tl:
        return True
    if re.match(r"^(why does|what is|how to|best way to)\b", tl):
        return True
    return False


def main(dry_run=False):
    index = json.loads(INDEX.read_text(encoding="utf-8"))

    # Recover full content for classification from the queue.
    title_map = {}
    for j in PUB.glob("*.json"):
        try:
            d = json.loads(j.read_text(encoding="utf-8"))
            title_map[d.get("title", "").strip().lower()] = d
        except Exception:
            pass

    junk, keep = [], []
    for a in index:
        src = title_map.get(a["title"].strip().lower(), {})
        probe = {"title": a.get("title", ""), "content": src.get("content", ""),
                 "keyword": a.get("keyword", "")}
        (junk if is_junk(probe) else keep).append(a)

    print(f"total articles : {len(index)}")
    print(f"KEEP           : {len(keep)}")
    print(f"PURGE (junk)   : {len(junk)}\n")
    for a in junk:
        print(f"   - {a['slug']}")

    if dry_run:
        print("\n[dry-run] no changes written")
        return 0

    if not junk:
        print("nothing to purge")
        return 0

    # 1. Remove HTML files
    removed_files = 0
    for a in junk:
        f = BLOG / f"{a['slug']}.html"
        if f.exists():
            f.unlink()
            removed_files += 1

    # 2. Rewrite index.json (drives the blog list AND sitemap.xml)
    INDEX.write_text(json.dumps(keep, indent=2, ensure_ascii=False), encoding="utf-8")

    # 3. Write the retired-slug manifest (source of truth for redirects)
    existing = {}
    if MANIFEST.exists():
        existing = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for a in junk:
        existing[a["slug"]] = a.get("title", "")
    MANIFEST.write_text(json.dumps(existing, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"\n[OK] deleted {removed_files} html file(s)")
    print(f"[OK] index.json now has {len(keep)} articles")
    print(f"[OK] {len(existing)} retired slug(s) in {MANIFEST.name}")
    print(f"[!]  ADD the redirect table to scanner_web.py ({REDIRECT_NOTE})")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    raise SystemExit(main(a.dry_run))